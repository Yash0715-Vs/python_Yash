def rectangle(length, width):
    area = length * width
    perimeter = 2 * (length + width)

    print(f"Area = {area}")
    print(f"Perimeter = {perimeter}")

# Function call
rectangle(10, 5)

def calculator(a, b):
    add = a+b
    sub = a-b
    multiply = a*b
    div = a/b

    print(f"the add is: {add}")
    print(f"the sub is: {sub}")
    print(f"the multiply is: {multiply}")
    print(f"the div is: {div}")

calculator(2,4)